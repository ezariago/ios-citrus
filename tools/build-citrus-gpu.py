#!/usr/bin/env python3
"""Build the opt-in Citrus GPU kernel separately; never flash or edit the root.

Requires the published build artifacts and the current Citrus baseline sources.
Without --firmware-dir, emit a probe-only kernel: full GPU start refuses to run.

Test profiles keep the unverified IOSurface/compositor backport out of the boot:
  --baseline-probe      SCM/GPUCC read-only query, baseline display/IOSurface/input
  --baseline-hardware   zap + SMMU + CP + 16-IB fence self-test, no GPU service
  --baseline-service    the same self-test plus RedwoodGPU publication, baseline
                        display/AMFI, patched SweetSurface (the service's surface
                        contract)
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import shlex
import shutil
import struct
import subprocess

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / 'out/upstream-artifacts/buildtree/xnu'
OUT = ROOT / 'out/citrus-gpu'
PATCH = ROOT / 'kernel/patches/0003-citrus-adreno-kernel.patch'


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def firmware(directory, source):
    blobs = {}
    names = {'zap_mdt': 'a610_zap.mdt', 'zap_b02': 'a610_zap.b02', 'sqe_fw': 'a630_sqe.fw'}
    for key, name in names.items():
        blobs[key] = (directory / name).read_bytes() if directory else b''
    if directory:
        mdt = blobs['zap_mdt']
        if len(mdt) < 52 or mdt[:7] != b'\x7fELF\x01\x01\x01':
            raise ValueError('zap MDT must be little-endian ELF32')
        phoff = struct.unpack_from('<I', mdt, 28)[0]
        phsize, count = struct.unpack_from('<HH', mdt, 42)
        if phsize != 32 or not count or phoff + count * 32 > len(mdt):
            raise ValueError('invalid zap program-header bounds')
        segments = []
        for i in range(count):
            typ, _, _, pa, size, memsize, flags, _ = struct.unpack_from('<8I', mdt, phoff + i * 32)
            if typ == 1 and memsize and (flags >> 24) & 7 != 2:
                segments.append((i, pa, size, memsize))
        if len(segments) != 1 or segments[0][0] != 2:
            raise ValueError('expected one load segment, a610_zap.b02')
        _, pa, size, memsize = segments[0]
        if size != len(blobs['zap_b02']) or size > memsize or memsize > 0x2000 or pa + memsize > 0xffffffff:
            raise ValueError('zap segment exceeds reserved 8 KiB or has wrong file size')
        if len(mdt) > 16384 or len(blobs['sqe_fw']) <= 4 or len(blobs['sqe_fw']) % 4:
            raise ValueError('invalid MDT/SQE size')
    lines = ['/* Generated by tools/build-citrus-gpu.py; never use Topaz firmware implicitly. */',
             '#include <stdint.h>', '#include <stddef.h>', 'extern "C" {']
    records = {}
    for key, data in blobs.items():
        lines.append(f'extern const uint8_t topaz_fw_{key}[] = {{')
        for i in range(0, len(data), 16):
            lines.append('    ' + ','.join(f'0x{x:02x}' for x in data[i:i + 16]) + ',')
        if not data:
            lines.append('    0,')
        lines += ['};', f'extern const size_t topaz_fw_{key}_size = {len(data)};']
        records[names[key]] = {'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest(),
                               'source': str(directory / names[key]) if directory else None}
    lines.append('}')
    (source / 'iokit/Kernel/arm/TopazAdrenoFw.cpp').write_text('\n'.join(lines) + '\n')
    return records


def compile_new(build, component, target, template, rel):
    command = json.loads((OUT / (template + '.command.json')).read_text())
    # Reuse exact XNU language/ABI flags; only the source, dependency and output change.
    template_source = next(x for x in command if x.endswith(('.cpp', '.c')) and not x.startswith('-'))
    command = [str(build.SOURCE / rel) if x == template_source else
               str(OUT / target) if x == str(OUT / template) else x for x in command]
    for flag in ('-o', '-MF'):
        for i, value in enumerate(command[:-1]):
            if value == flag:
                command[i + 1] = str(OUT / (target if flag == '-o' else target + '.d'))
    (OUT / (target + '.command.json')).write_text(json.dumps(command, indent=2) + '\n')
    work = build.TREE / 'build/xnu.obj/DEVELOPMENT_ARM64_SWEET' / component / 'DEVELOPMENT'
    result = subprocess.run(command, cwd=work, capture_output=True, text=True)
    (OUT / (target + '.compile.log')).write_text(result.stdout + result.stderr)
    if result.returncode:
        raise RuntimeError(f'{target}: {result.stderr[-5000:]}')
    print('Compiled ' + target, flush=True)


def main():
    global OUT
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--firmware-dir', type=Path, help='Citrus vendor firmware directory (record provenance separately)')
    parser.add_argument('--prepare-only', action='store_true')
    parser.add_argument('--output-dir', type=Path, help='separate build directory; preserves existing test builds')
    parser.add_argument('--baseline-probe', action='store_true', help='SCM-only diagnostic with baseline display/IOSurface/input')
    parser.add_argument('--baseline-hardware', action='store_true', help='GPU firmware/CP self-test with baseline display/input, no GPU service')
    parser.add_argument('--baseline-service', action='store_true',
                        help='GPU self-test + RedwoodGPU service with baseline display/AMFI (patched SweetSurface kept)')
    parser.add_argument('--baseline-compositor', action='store_true',
                        help='GPU service + AMFI dyld policy with baseline display (first CoreAnimation test)')
    args = parser.parse_args()
    if sum((args.baseline_probe, args.baseline_hardware, args.baseline_service, args.baseline_compositor)) > 1:
        parser.error('choose only one baseline test mode')
    if (args.baseline_hardware or args.baseline_service or args.baseline_compositor) and not args.firmware_dir:
        parser.error('--baseline-hardware/--baseline-service require device firmware')
    if args.baseline_probe:
        if args.firmware_dir:
            parser.error('--baseline-probe does not use firmware')
        OUT = ROOT / 'out/citrus-gpu-baseline-probe'
    elif args.baseline_hardware:
        OUT = ROOT / 'out/citrus-gpu-baseline-hardware'
    elif args.baseline_service:
        OUT = ROOT / 'out/citrus-gpu-baseline-service'
    elif args.baseline_compositor:
        OUT = ROOT / 'out/citrus-gpu-baseline-compositor'
    if args.output_dir:
        OUT = args.output_dir.resolve()
    expected = json.loads((ROOT / 'research/citrus-gpu-source-manifest.json').read_text())
    if sha(PATCH) != expected['patch_sha256']:
        raise SystemExit('GPU patch hash differs from its manifest')
    for rel, digest in expected['base_files'].items():
        if sha(BASE / rel) != digest:
            raise SystemExit(f'baseline changed: {rel}; rebase GPU patch before building')
    OUT.mkdir(parents=True, exist_ok=True)
    source = OUT / 'xnu'
    if source.exists():
        shutil.rmtree(source)
    shutil.copytree(BASE, source)
    if not args.baseline_probe:
        result = subprocess.run(['patch', '-p1', '--batch', '--fuzz=0', '-i', str(PATCH)],
                                cwd=source, capture_output=True, text=True)
        (OUT / 'patch.log').write_text(result.stdout + result.stderr)
        if result.returncode:
            raise SystemExit('GPU patch failed; see patch.log')
    if args.baseline_probe or args.baseline_hardware or args.baseline_service or args.baseline_compositor:
        # Isolate hardware bring-up from the unverified IOSurface/compositor backport.
        # The service needs the patched SweetSurface (GPU pool fields, state values);
        # the display and AMFI backport is what froze the probe1 UI, so it stays out.
        if args.baseline_hardware:
            for rel in ('iokit/Kernel/arm/SweetFramebuffer.cpp', 'iokit/Kernel/arm/SweetSurface.cpp',
                        'iokit/Kernel/arm/SweetSurface.h', 'bsd/kern/sweet_amfi.c'):
                shutil.copyfile(BASE / rel, source / rel)
        elif args.baseline_service:
            for rel in ('iokit/Kernel/arm/SweetFramebuffer.cpp', 'bsd/kern/sweet_amfi.c'):
                shutil.copyfile(BASE / rel, source / rel)
        elif args.baseline_compositor:
            # Keep only the display path out of the unverified backport; the
            # patched sweet_amfi.c is required for the citrusgl dyld policy.
            rel = 'iokit/Kernel/arm/SweetFramebuffer.cpp'
            baseline_fb = (BASE / rel).read_text()
            # QuartzCore reads the six halves as {refresh time, presented time,
            # counter}. The original baseline published the counter first, which
            # makes CA's frame clock treat 1,2,3 as times (reported as
            # rubber-banding animations). Publish the full backport's order only.
            old_values = ('\tuint64_t values[6] = {\n'
                          '\t\t(uint32_t)count, (uint32_t)(count >> 32),\n'
                          '\t\t(uint32_t)now, (uint32_t)(now >> 32),\n'
                          '\t\t0, 0,\n'
                          '\t};')
            new_values = ('\tuint64_t values[6] = {\n'
                          '\t\t(uint32_t)now, (uint32_t)(now >> 32),\n'
                          '\t\t(uint32_t)now, (uint32_t)(now >> 32),\n'
                          '\t\t(uint32_t)count, (uint32_t)(count >> 32),\n'
                          '\t};')
            if old_values not in baseline_fb:
                raise SystemExit('baseline vsync timestamp anchor missing')
            (source / rel).write_text(baseline_fb.replace(old_values, new_values, 1))
        entry = 'citrus_gpu_probe_init' if args.baseline_probe else 'topaz_adreno_init'
        cpp = source / 'iokit/Kernel/arm/SweetFramebuffer.cpp'
        text = cpp.read_text()
        include = '#include "SweetSurface.h"'
        if include not in text:
            raise SystemExit('baseline framebuffer include anchor missing')
        text = text.replace(include, include + f'\nextern "C" void {entry}(void);', 1)
        anchor = '\tfCtl0 = (volatile uint32_t *)ml_io_map(0x05e02000, 0x1000);'
        if anchor not in text:
            raise SystemExit('baseline framebuffer init anchor missing')
        cpp.write_text(text.replace(anchor, anchor + f'\n\t{entry}();', 1))
        if args.baseline_probe:
            shutil.copyfile(ROOT / 'kernel/drivers/CitrusGpuProbe.cpp', source / 'iokit/Kernel/arm/CitrusGpuProbe.cpp')
        elif args.baseline_hardware:
            driver = source / 'iokit/Kernel/arm/TopazAdreno.cpp'
            text = driver.read_text()
            # Hardware mode omits the client service; the canonical driver now
            # uses the PAS path validated by Citrus hw2, including advisory query.
            text = text.replace('    RedwoodGPUStart();', '    IOLog("CitrusGPU: hardware selftest complete; baseline UI retained, no service published\\n");', 1)
            text = text.replace('\tIOLog("TopazGPU: Adreno 610 ready, RedwoodGPU published\\n");', '')
            driver.write_text(text)
    records = firmware(args.firmware_dir.resolve() if args.firmware_dir else None, source)
    manifest = {'hardware_tested': False, 'firmware': records, 'patch_sha256': sha(PATCH),
                'baseline_patch_sha256': sha(ROOT / 'kernel/patches/0002-sweet-console-display-stall-instrumentation.patch'),
                'page_size': 16384, 'gpu_default': 'off', 'raw_physical_pool': 'disabled',
                'baseline_probe': args.baseline_probe, 'baseline_hardware': args.baseline_hardware,
                'baseline_service': args.baseline_service, 'baseline_compositor': args.baseline_compositor,
                'vsync_timestamps': 'now,now,count' if args.baseline_compositor else 'baseline'}
    if args.baseline_probe:
        manifest['probe_source_sha256'] = sha(ROOT / 'kernel/drivers/CitrusGpuProbe.cpp')
    if args.baseline_hardware or args.baseline_service or args.baseline_compositor:
        manifest['hardware_driver_sha256'] = sha(source / 'iokit/Kernel/arm/TopazAdreno.cpp')
    provenance = args.firmware_dir / 'provenance.json' if args.firmware_dir else None
    if provenance and provenance.exists():
        manifest['firmware_provenance'] = json.loads(provenance.read_text())
    (OUT / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    if args.prepare_only:
        print('Prepared ' + str(source))
        return
    spec = importlib.util.spec_from_file_location('citrus_rebuild', ROOT / 'tools/rebuild-kernel.py')
    build = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(build)
    build.OUT, build.SOURCE = OUT, source
    # Compile the baseline too: no stale touch, display or observer objects.
    targets = [('pexpert', 'pe_fiq.o'), ('osfmk', 'sweet_early.o'), ('osfmk', 'start.o'),
               ('osfmk', 'arm_vm_init.o'), ('iokit', 'SweetBattery.cpo'),
               ('osfmk', 'serial_console.o'), ('iokit', 'SweetFramebuffer.cpo'),
               ('iokit', 'SweetSurface.cpo'), ('osfmk', 'exception.o'), ('osfmk', 'rtclock.o'),
               ('osfmk', 'video_console.o'), ('bsd', 'sweet_sample.o'), ('osfmk', 'cpu.o'),
               ('bsd', 'sweet_ufs.o'), ('bsd', 'sweet_usb.o'), ('bsd', 'sweet_touch.o'),
               ('bsd', 'sweet_cpufreq.o')]
    for component, target in targets:
        build.compile_object(component, target)
    extra = ('CitrusGpuProbe',) if args.baseline_probe else \
            ('TopazAdreno', 'TopazAdrenoFw') if args.baseline_hardware else \
            ('TopazAdreno', 'RedwoodGPU', 'TopazAdrenoFw')
    for name in extra:
        compile_new(build, 'iokit', name + '.cpo', 'SweetFramebuffer.cpo', 'iokit/Kernel/arm/' + name + '.cpp')
        targets.append(('iokit', name + '.cpo'))
    if not args.baseline_probe:
        compile_new(build, 'bsd', 'topaz_fw.o', 'sweet_sample.o', 'bsd/dev/topaz_fw.c')
        targets.append(('bsd', 'topaz_fw.o'))
        if not (args.baseline_hardware or args.baseline_service):
            compile_new(build, 'bsd', 'sweet_amfi.o', 'sweet_sample.o', 'bsd/kern/sweet_amfi.c')
            targets.append(('bsd', 'sweet_amfi.o'))
    link = build.ART / 'xnu-kernel/kernel.development.sweet.link'
    archive = OUT / 'citrus.a'
    shutil.copyfile(link / 'kernel.development.sweet.a', archive)
    manifest['upstream_archive_sha256'] = sha(link / 'kernel.development.sweet.a')
    subprocess.run(['/opt/homebrew/opt/llvm/bin/llvm-ar', 'r', str(archive),
                    *[str(OUT / name) for _, name in targets]], check=True)
    arguments = shlex.split((link / 'kernel.development.sweet.linkarguments').read_text())
    arguments = [x for x in arguments if not x.startswith('-L/Users/runner/') and x not in
                 ['-lfirehose_kernel', '-lcc_kext', '-Wl,-rename_segment,__LASTDATA_CONST,__LAST']]
    runtime = subprocess.check_output(['xcrun', 'clang', '--print-file-name=libclang_rt.cc_kext.a'], text=True).strip()
    kernel = OUT / 'kernel.development.citrus'
    arguments += [runtime, str(build.ART / 'firehose_buffer.o'), '-Wl,-force_load,' + str(archive),
                  '-Wl,-exported_symbols_list,' + str(link / 'kernel.development.sweet.exp'),
                  '-Wl,-alias_list,' + str(link / 'kernel.development.sweet.alias.exp'), '-o', str(kernel)]
    result = subprocess.run(['xcrun', 'clang', *arguments], capture_output=True, text=True)
    (OUT / 'link.log').write_text(result.stdout + result.stderr)
    if result.returncode:
        raise SystemExit(result.stderr[-5000:])
    manifest['kernel_sha256'] = sha(kernel)
    manifest['objects'] = {name: sha(OUT / name) for _, name in targets}
    (OUT / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print('Linked ' + str(kernel), flush=True)


if __name__ == '__main__':
    main()
