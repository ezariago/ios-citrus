#!/usr/bin/env python3
"""Embed the vendor FT8719 application image into the kernel probe.

Source blob: devices/citrus-ft8719-fw.bin, the ``focaltech_ts_fw.bin`` that the
OrangeFox "juice" recovery tree ships in /vendor/firmware (the same file name
the vendor focaltech_flash.c requests through request_firmware()).  The FT8719
is a RAM-only incell IC: the boot ROM runs after reset and the driver has to
download this image into PRAM before the touch application starts.

The binary is a container: byte 0x100 holds the big-endian PRAM application
length and its one's complement at 0x102 (fts_pram_write_ecc() checks that the
two add up to 0xffff).  Only that leading slice is written to PRAM.

Output: bsd/dev/sweet_touch_fw.h in the build tree, a plain byte array.
"""
import argparse
import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / 'devices/citrus-ft8719-fw.bin'
DST = ROOT / 'out/upstream-artifacts/buildtree/xnu/bsd/dev/sweet_touch_fw.h'
APP_INFO_OFFSET = 0x100


def build(src=SRC):
    data = src.read_bytes()
    if len(data) < APP_INFO_OFFSET + 4:
        raise SystemExit(f'{src}: too short')
    code_len = (data[APP_INFO_OFFSET] << 8) | data[APP_INFO_OFFSET + 1]
    code_len_n = (data[APP_INFO_OFFSET + 2] << 8) | data[APP_INFO_OFFSET + 3]
    if code_len + code_len_n != 0xffff:
        raise SystemExit(f'{src}: bad app length pair {code_len:#x}/{code_len_n:#x}')
    if code_len == 0 or code_len > len(data):
        raise SystemExit(f'{src}: app length {code_len} outside the file')
    app = data[:code_len]
    out = []
    out.append('/* Generated by tools/embed-touch-fw.py -- do not edit.')
    out.append(' * Source: devices/citrus-ft8719-fw.bin')
    out.append(f' * sha256 {hashlib.sha256(data).hexdigest()}')
    out.append(f' * PRAM application length {code_len} bytes. */')
    out.append('static const unsigned char citrus_ft8719_fw[] =')
    for i in range(0, len(app), 64):
        chunk = app[i:i + 64]
        out.append('    "' + ''.join('\\x%02x' % b for b in chunk) + '"')
    out.append('    ;')
    out.append(f'static const unsigned int citrus_ft8719_fw_len = {len(app)}u;')
    out.append('')
    return '\n'.join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true',
                    help='fail if the generated header is out of date')
    args = ap.parse_args()
    text = build()
    if args.check:
        if not DST.exists() or DST.read_text() != text:
            print(f'{DST} is stale; run tools/embed-touch-fw.py', file=sys.stderr)
            raise SystemExit(1)
        print(f'{DST} is current')
        return
    DST.parent.mkdir(parents=True, exist_ok=True)
    DST.write_text(text)
    print(f'wrote {DST} ({len(text)} bytes of source)')


if __name__ == '__main__':
    main()
